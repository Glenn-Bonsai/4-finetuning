import os
import json
import time
import random
from datasets import load_dataset
from openai import OpenAI
from tqdm import tqdm
from google.colab import userdata

os.environ["OPENAI_API_KEY"] = userdata.get("OPENAI_API_KEY")
client = OpenAI()

"""## 데이터셋 로딩"""

dataset = load_dataset("krasaee/nietzsche", split="train")
print(dataset)
print(dataset[0])

"""## 전처리
- 청킹 없이 문장 단위 그대로 사용
- 너무 짧은 문장(단어 5개 미만)만 제거
"""

# 유효한 문장만 추출 (너무 짧은 것 제거)
texts = [
    row["text"].strip()
    for row in dataset
    if len(row["text"].strip().split()) >= 5
]
print(f"유효한 문장 수: {len(texts)}")
print(f"샘플: {texts[0]}")

# 목표: 150개 문장 선택 → 문장당 QA 3개 = 450개
TARGET_QA_PER_SENTENCE = 3
TARGET_SENTENCES = 150

random.seed(42)
selected_indices = sorted(random.sample(range(len(texts)), min(TARGET_SENTENCES, len(texts))))
print(f"선택된 문장 수: {len(selected_indices)}")

"""## 한국어 QA 생성"""

SYSTEM_PROMPT = """당신은 니체 철학 전문가입니다.
주어진 니체 원문을 바탕으로 한국어 QA 쌍을 생성합니다.

output(답변) 작성 규칙:
- 니체 1인칭 시점
- 원문의 논지를 답변의 근거로 삼는 것이 최우선
- 답변 길이: 3문장 이내"""

USER_TEMPLATE = """다음 니체 원문을 바탕으로 한국어 QA 쌍 {n}개를 JSON 배열로 생성해줘.

규칙:
- 질문은 반드시 아래 [핵심 문장]이 직접 다루는 내용에서만 만들 것
- 원문의 논지를 답변 근거로 삼되, 직접 인용은 금지

[핵심 문장]
{sentence}

형식:
[
  {{
    "instruction": "철학자 니체의 시각으로 질문에 답하는 챗봇입니다. 니체의 철학적 문체로 한국어로 답하세요.",
    "input": "사용자 질문",
    "output": "니체 1인칭 한국어 답변"
  }}
]

주의: JSON 배열만 출력하고, 다른 텍스트는 포함하지 마세요."""

def generate_qa(idx: int, n: int = 3, max_retries: int = 3) -> list[dict]:
    sentence = texts[idx]

    for attempt in range(max_retries):
        try:
            response = client.chat.completions.create(
                model="gpt-4o-mini",
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": USER_TEMPLATE.format(
                        n=n,
                        sentence=sentence
                    )}
                ],
                temperature=0.8,
                max_tokens=1500,
            )
            content = response.choices[0].message.content.strip()

            # JSON 파싱
            if content.startswith("```"):
                content = content.split("```")[1]
                if content.startswith("json"):
                    content = content[4:]

            qa_pairs = json.loads(content)

            # 필수 키 검증
            validated = [
                qa for qa in qa_pairs
                if all(k in qa for k in ["instruction", "input", "output"])
                and len(qa["input"]) > 5
                and len(qa["output"]) > 50
            ]
            return validated

        except (json.JSONDecodeError, Exception) as e:
            print(f"  재시도 {attempt+1}/{max_retries}: {e}")
            time.sleep(2 ** attempt)
    return []

# 소규모 테스트 (3개 문장)
print("=== API 테스트 (3개 문장) ===")
test_results = []
for idx in selected_indices[:3]:
    qa_pairs = generate_qa(idx, n=TARGET_QA_PER_SENTENCE)
    test_results.extend(qa_pairs)
    print(f"생성된 QA: {len(qa_pairs)}개")

print(f"\n총 테스트 결과: {len(test_results)}개")
print("\n--- 샘플 출력 ---")
print(json.dumps(test_results[0], ensure_ascii=False, indent=2))

# 전체 생성 (테스트 확인 후 실행)
all_qa_pairs = []
failed_indices = []

for idx in tqdm(selected_indices, desc="QA 생성 중"):
    qa_pairs = generate_qa(idx, n=TARGET_QA_PER_SENTENCE)
    if qa_pairs:
        all_qa_pairs.extend(qa_pairs)
    else:
        failed_indices.append(idx)
    time.sleep(0.5)  # API rate limit 방지

print(f"\n생성 완료: {len(all_qa_pairs)}개")
print(f"실패한 문장: {len(failed_indices)}개")

"""## 검수 & 저장"""

# 중복 제거 (input 기준)
seen_inputs = set()
deduplicated = []
for qa in all_qa_pairs:
    if qa["input"] not in seen_inputs:
        seen_inputs.add(qa["input"])
        deduplicated.append(qa)

# 길이 필터
final_dataset = [
    qa for qa in deduplicated
    if len(qa["output"]) >= 50
]

print(f"중복 제거 전: {len(all_qa_pairs)}개")
print(f"중복 제거 후: {len(deduplicated)}개")
print(f"최종 데이터셋: {len(final_dataset)}개")

# 샘플 10개
samples = random.sample(final_dataset, min(10, len(final_dataset)))
for i, qa in enumerate(samples):
    print(f"[{i+1}] Q: {qa['input']}")
    print(f"     A: {qa['output']}")
    print()

